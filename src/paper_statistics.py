import json
import math
import re
from collections import defaultdict
from pathlib import Path
from typing import Any, Iterable, Mapping, Sequence

import numpy as np

DEFAULT_INPUT = Path("results/paper_benchmarks/paper_benchmark_results.json")
DEFAULT_OUTPUT_DIR = Path("paper/tables")
RGSA_CONFIG = "random_guided_sa"
PIPELINE_CONFIG = "full_esa"
LAGBLIND_CONFIG = "lagrangian_blind_sa"
REFERENCE_CONFIG = "random_blind_sa"
CONFIG_ORDER = (
    REFERENCE_CONFIG,
    LAGBLIND_CONFIG,
    RGSA_CONFIG,
    PIPELINE_CONFIG,
)
CONFIG_LABELS = {
    REFERENCE_CONFIG: "Blind SA",
    LAGBLIND_CONFIG: "Lagrangian + Blind SA",
    RGSA_CONFIG: "RGSA",
    PIPELINE_CONFIG: "Full RGSA pipeline",
}
REPRESENTATIVE_INSTANCE = "ms_15_200_000"
BOOTSTRAP_RESAMPLES = 10_000
BOOTSTRAP_SEED = 42

WASSERMANN_TIMES: dict[tuple[int, int], float | None] = {
    (9, 50): 0.00,
    (10, 50): 0.00,
    (11, 50): 24.00,
    (12, 50): 617.00,
    (13, 50): 5_365.00,
    (14, 50): 140_823.00,
    (15, 50): None,
    (15, 200): None,
}

KEMPKE_TIMES: dict[tuple[int, int], float | None] = {
    (9, 50): 236.07,
    (10, 50): 66_636.22,
}

_INSTANCE_RE = re.compile(r"(?:^|/)ms_(\d+)_(\d+)_(\d+)(?:\.dat)?$")


def _first_present(record: Mapping[str, Any], names: Sequence[str]) -> Any:
    for name in names:
        if name in record:
            return record[name]
    raise KeyError("/".join(names))


def _as_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)) and value in (0, 1):
        return bool(value)
    if isinstance(value, str):
        normalized = value.strip().lower()
        if normalized in {"true", "yes", "1"}:
            return True
        if normalized in {"false", "no", "0"}:
            return False
    raise ValueError(f"invalid feasibility value: {value!r}")


def _extract_records(payload: Any) -> list[Mapping[str, Any]]:
    if isinstance(payload, list):
        records = payload
    elif isinstance(payload, dict):
        records = None
        for key in ("results", "runs", "benchmark_results"):
            if key in payload:
                records = payload[key]
                break
        if records is None:
            raise ValueError(
                "JSON object must contain a list under 'results', 'runs', "
                "or 'benchmark_results'"
            )
    else:
        raise ValueError("benchmark JSON must be a list or object containing a run list")
    if not isinstance(records, list):
        raise ValueError("benchmark run collection must be a JSON list")
    if not all(isinstance(item, dict) for item in records):
        raise ValueError("every benchmark run must be a JSON object")
    return records


def load_results(path: str | Path) -> list[dict[str, Any]]:
    """Load and normalize paper benchmark run records from *path*."""
    input_path = Path(path)
    with input_path.open("r", encoding="utf-8") as handle:
        raw_records = _extract_records(json.load(handle))

    normalized: list[dict[str, Any]] = []
    for index, raw in enumerate(raw_records):
        try:
            instance_value = _first_present(raw, ("instance", "instance_name", "instance_file"))
            config = str(_first_present(raw, ("config", "configuration", "config_name")))
            seed = _first_present(raw, ("seed", "random_seed"))
            residual = float(_first_present(raw, ("final_residual",)))
            total_time = float(_first_present(raw, ("total_time_sec", "time_sec")))
            feasible = _as_bool(_first_present(raw, ("feasible",)))
        except (KeyError, TypeError, ValueError) as exc:
            raise ValueError(f"invalid run record at index {index}: {exc}") from exc

        instance = Path(str(instance_value)).name
        if instance.endswith(".dat"):
            instance = instance[:-4]
        match = _INSTANCE_RE.search(str(instance_value)) or _INSTANCE_RE.search(instance)
        try:
            m = int(raw["m"]) if "m" in raw else int(match.group(1))
            D = int(raw["D"]) if "D" in raw else int(match.group(2))
        except (AttributeError, TypeError, ValueError) as exc:
            raise ValueError(
                f"invalid run record at index {index}: cannot determine m and D "
                f"from instance {instance_value!r}"
            ) from exc

        if not config:
            raise ValueError(f"invalid run record at index {index}: config is empty")
        if not math.isfinite(residual) or residual < 0:
            raise ValueError(f"invalid run record at index {index}: final_residual must be finite and nonnegative")
        if not math.isfinite(total_time) or total_time < 0:
            raise ValueError(f"invalid run record at index {index}: total_time_sec must be finite and nonnegative")

        normalized.append(
            {
                **raw,
                "instance": instance,
                "config": config,
                "seed": seed,
                "m": m,
                "D": D,
                "final_residual": residual,
                "total_time_sec": total_time,
                "feasible": feasible,
            }
        )
    return normalized


def _descriptive_statistics(values: Iterable[float]) -> dict[str, float | int]:
    data = np.asarray(list(values), dtype=float)
    if data.size == 0:
        raise ValueError("cannot compute statistics for an empty group")
    std = float(np.std(data, ddof=1)) if data.size > 1 else 0.0
    return {
        "count": int(data.size),
        "mean": float(np.mean(data)),
        "median": float(np.median(data)),
        "std": std,
        "min": float(np.min(data)),
        "max": float(np.max(data)),
    }


def compute_per_class_statistics(
    runs: Sequence[Mapping[str, Any]],
) -> dict[tuple[int, int, str], dict[str, float | int]]:
    """Aggregate residuals, times, violations, and feasibility by (m, D, config)."""
    groups: dict[tuple[int, int, str], list[Mapping[str, Any]]] = defaultdict(list)
    for run in runs:
        groups[(int(run["m"]), int(run["D"]), str(run["config"]))].append(run)

    result: dict[tuple[int, int, str], dict[str, float | int]] = {}
    for key, group in sorted(groups.items()):
        stats = _descriptive_statistics(float(run["final_residual"]) for run in group)
        times = np.asarray([float(run["total_time_sec"]) for run in group], dtype=float)
        v_max_vals = np.asarray(
            [float(run.get("max_abs_violation", 0.0)) for run in group], dtype=float
        )
        stats.update(
            {
                "mean_time_sec": float(np.mean(times)),
                "std_time_sec": float(np.std(times, ddof=1)) if len(times) > 1 else 0.0,
                "feasibility_rate": float(np.mean([bool(run["feasible"]) for run in group])),
                "mean_v_max": float(np.mean(v_max_vals)),
                "std_v_max": float(np.std(v_max_vals, ddof=1)) if len(v_max_vals) > 1 else 0.0,
            }
        )
        result[key] = stats
    return result


def paired_bootstrap_ci(
    differences: Sequence[float],
    *,
    n_resamples: int = BOOTSTRAP_RESAMPLES,
    confidence: float = 0.95,
    seed: int = BOOTSTRAP_SEED,
) -> tuple[float, float]:
    """Bootstrap a confidence interval for the mean of paired differences."""
    values = np.asarray(differences, dtype=float)
    if values.size == 0:
        raise ValueError("paired bootstrap requires at least one difference")
    if n_resamples <= 0:
        raise ValueError("n_resamples must be positive")
    if not 0.0 < confidence < 1.0:
        raise ValueError("confidence must lie strictly between zero and one")

    rng = np.random.default_rng(seed)
    means: list[np.ndarray] = []
    remaining = n_resamples
    while remaining:
        chunk_size = min(remaining, 2_000)
        indices = rng.integers(0, values.size, size=(chunk_size, values.size))
        means.append(values[indices].mean(axis=1))
        remaining -= chunk_size
    bootstrap_means = np.concatenate(means)
    alpha = (1.0 - confidence) / 2.0
    lower, upper = np.quantile(bootstrap_means, [alpha, 1.0 - alpha])
    return float(lower), float(upper)


def _paired_differences(
    runs: Sequence[Mapping[str, Any]], config_a: str, config_b: str
) -> list[float]:
    """Compute paired differences (config_a - config_b) for matched (instance, seed)."""
    by_config: dict[str, dict[tuple[str, Any], float]] = defaultdict(dict)
    for run in runs:
        key = (str(run["instance"]), run["seed"])
        config = str(run["config"])
        if key in by_config[config]:
            raise ValueError(f"duplicate (instance, seed, config) run for {key + (config,)}")
        by_config[config][key] = float(run["final_residual"])

    common = sorted(
        set(by_config.get(config_a, {})) & set(by_config.get(config_b, {})),
        key=lambda item: (item[0], str(item[1])),
    )
    return [by_config[config_a][key] - by_config[config_b][key] for key in common]


def compute_improvement_stats(
    runs: Sequence[Mapping[str, Any]],
    *,
    method: str = RGSA_CONFIG,
    baseline: str = REFERENCE_CONFIG,
    seed: int = BOOTSTRAP_SEED,
) -> dict[str, float | int]:
    """Return headline statistics: baseline - method (positive = method better)."""
    diffs = _paired_differences(runs, baseline, method)
    diffs_arr = np.asarray(diffs, dtype=float)
    lower, upper = paired_bootstrap_ci(diffs, seed=seed)
    n_better = int(np.sum(diffs_arr > 0))
    return {
        "n_pairs": len(diffs),
        "mean_improvement": float(np.mean(diffs_arr)),
        "median_improvement": float(np.median(diffs_arr)),
        "ci_lower": lower,
        "ci_upper": upper,
        "n_better": n_better,
        "n_total": len(diffs),
    }


def _format_number(value: float, precision: int = 3) -> str:
    magnitude = abs(value)
    if magnitude != 0 and (magnitude < 10 ** (-precision) or magnitude >= 1_000_000):
        return f"{value:.{precision}e}"
    return f"{value:.{precision}f}"


def _format_time(value: float | None) -> str:
    return "--" if value is None else f"{value:.2f}"


def _latex_escape(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
    }
    return "".join(replacements.get(char, char) for char in text)


def _row_key_sort(item):
    m, D = item[0], item[1]
    return (m, D)


