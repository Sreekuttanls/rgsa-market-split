def generate_scaling_table(
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
) -> str:
    """RGSA scaling study: rows = (m, D) for RGSA_CONFIG only."""
    rows = []
    for (m, D, config), stats in sorted(class_statistics.items()):
        if config != RGSA_CONFIG:
            continue
        residual = (
            f"${_format_number(float(stats['mean']))} \\pm "
            f"{_format_number(float(stats['std']))}$"
        )
        rows.append(
            f"{m} & {D} & {residual} & {_format_time(float(stats['mean_time_sec']))} "
            + r"\\"
        )

    body = "\n".join(rows) if rows else r"\multicolumn{4}{c}{No RGSA results} \\"
    return f"""% Generated by src/paper_statistics.py
\\begin{{table}}[htbp]
\\centering
\\caption{{RGSA scaling study. Residuals and run times are aggregated across seeds.}}
\\label{{tab:rgsa-scaling}}
\\begin{{tabular}}{{rrrr}}
\\toprule
$m$ & $D$ & Final residual (mean $\\pm$ std.) & Mean time (s) \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def generate_comprehensive_table(
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
) -> str:
    """Comprehensive comparison: all configs across all classes.  Bold = best (min residual)."""
    # Collect unique (m, D) classes
    classes = sorted({(m, D) for (m, D, _) in class_statistics.keys()}, key=_row_key_sort)

    # Find best residual per class
    best_per_class: dict[tuple[int, int], float] = {}
    for (m, D, config), stats in class_statistics.items():
        key = (m, D)
        val = float(stats["mean"])
        if key not in best_per_class or val < best_per_class[key]:
            best_per_class[key] = val

    rows = []
    for m, D in classes:
        cells = []
        impr = None
        for config in CONFIG_ORDER:
            stats = class_statistics.get((m, D, config))
            if stats is None:
                cells.append("--")
                continue
            mean = float(stats["mean"])
            std = float(stats["std"])
            time_s = float(stats["mean_time_sec"])
            is_best = abs(mean - best_per_class[(m, D)]) < 1e-12
            resid_str = f"{mean:.1f}\\text{{\\small$\\pm${std:.1f}}}"
            if is_best:
                resid_str = f"\\mathbf{{{resid_str}}}"
            cells.append(f"${resid_str}$")
            cells.append(f"{time_s:.0f}")
            # Compute improvement vs blind
            if config == RGSA_CONFIG:
                blind_stats = class_statistics.get((m, D, REFERENCE_CONFIG))
                if blind_stats:
                    impr = round(
                        (float(blind_stats["mean"]) - mean) / float(blind_stats["mean"]) * 100
                    )

        impr_str = f"{impr}\\%" if impr is not None else ""
        rows.append(
            f"{m} & {D} & "
            + " & ".join(cells)
            + f" & {impr_str} \\\\"
        )

    body = "\n".join(rows)
    return f"""% Generated by src/paper_statistics.py
\\begin{{table*}}[htbp]
\\centering
\\caption{{Comprehensive comparison of RGSA and the Full RGSA pipeline against baselines on QOBLIB Market Split instances.  Mean$\\pm$std of $\\ell_2$ residual $\\|Ax-b\\|_2$ over 5 seeds.  Bold = best method.  Time in seconds.}}
\\label{{tab:comprehensive}}
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{rr|rc|rc|rc|rc|r}}
\\toprule
 & & \\multicolumn{{2}}{{c|}}{{Blind SA}} & \\multicolumn{{2}}{{c|}}{{Lag.+Blind SA}} & \\multicolumn{{2}}{{c|}}{{RGSA}} & \\multicolumn{{2}}{{c|}}{{Full RGSA}} & \\\\
$m$ & $D$ & Resid. & $t$ & Resid. & $t$ & Resid. & $t$ & Resid. & $t$ & Impr. \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


def generate_best_residuals_table(
    runs: Sequence[Mapping[str, Any]],
) -> str:
    """Best achieved residuals: min over 5 seeds per method and class.  Bold = best."""
    # Compute min residual per (m, D, config)
    mins: dict[tuple[int, int, str], float] = {}
    for run in runs:
        key = (int(run["m"]), int(run["D"]), str(run["config"]))
        val = float(run["final_residual"])
        if key not in mins or val < mins[key]:
            mins[key] = val

    classes = sorted({(m, D) for (m, D, _) in mins.keys()}, key=_row_key_sort)
    best_per_class: dict[tuple[int, int], float] = {}
    for (m, D, config), val in mins.items():
        key = (m, D)
        if key not in best_per_class or val < best_per_class[key]:
            best_per_class[key] = val

    rows = []
    for m, D in classes:
        cells = []
        for config in CONFIG_ORDER:
            val = mins.get((m, D, config))
            if val is None:
                cells.append("--")
                continue
            cell = f"{val:.2f}"
            if abs(val - best_per_class[(m, D)]) < 1e-12:
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        rows.append(f"{m} & {D} & " + " & ".join(cells) + r" \\")

    body = "\n".join(rows)
    return f"""% Generated by src/paper_statistics.py
\\begin{{table}}[t]
\\centering
\\caption{{Best achieved residual $\\|Ax-b\\|_2$ (minimum over 5 seeds) per method and instance class.  A residual of 0 would indicate exact feasibility; no method achieved this.}}
\\label{{tab:best-residuals}}
\\small
\\begin{{tabular}}{{rr|rrrr}}
\\toprule
$m$ & $D$ & Blind SA & Lag+Blind & RGSA & Full RGSA \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def generate_ablation_table(
    runs: Sequence[Mapping[str, Any]], instance: str = REPRESENTATIVE_INSTANCE
) -> str:
    """Ablation study on the flagship instance."""
    selected = [run for run in runs if str(run["instance"]) == instance]
    configs = sorted({str(run["config"]) for run in selected})
    if REFERENCE_CONFIG in configs:
        configs.remove(REFERENCE_CONFIG)
        configs.insert(0, REFERENCE_CONFIG)

    rows = []
    for offset, config in enumerate(configs):
        config_runs = [run for run in selected if str(run["config"]) == config]
        stats = _descriptive_statistics(float(run["final_residual"]) for run in config_runs)
        residual = f"${_format_number(float(stats['mean']))} \\pm {_format_number(float(stats['std']))}$"

        if config == REFERENCE_CONFIG:
            ci_text = r"$[0.000,\, 0.000]$"
        else:
            # Positive = method better (reference - method)
            diffs = _paired_differences(selected, REFERENCE_CONFIG, config)
            if diffs:
                lower, upper = paired_bootstrap_ci(diffs, seed=BOOTSTRAP_SEED + offset)
                ci_text = f"$[{_format_number(lower)},\\, {_format_number(upper)}]$"
            else:
                ci_text = "--"
        rows.append(f"{_latex_escape(config)} & {residual} & {ci_text} " + r"\\")

    body = "\n".join(rows)
    escaped_instance = _latex_escape(instance)
    return f"""% Generated by src/paper_statistics.py
\\begin{{table}}[htbp]
\\centering
\\caption{{Ablation study on \\texttt{{{escaped_instance}}}.  Improvement is the paired baseline residual minus configuration residual; positive values favor the configuration.}}
\\label{{tab:rgsa-ablation}}
\\begin{{tabular}}{{lrr}}
\\toprule
Configuration & Final residual (mean $\\pm$ std.) & 95\\% CI of improvement \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def generate_literature_table(
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
) -> str:
    """RGSA vs exact-method runtimes.  Two method columns."""
    rows = []
    for (m, D, config), stats in sorted(class_statistics.items()):
        if config != RGSA_CONFIG:
            continue
        rows.append(
            f"{m} & {D} & {_format_number(float(stats['mean']))} & "
            f"{_format_time(float(stats['mean_time_sec']))} & "
            f"{_format_time(WASSERMANN_TIMES.get((m, D)))} & "
            f"{_format_time(KEMPKE_TIMES.get((m, D)))} "
            + r"\\"
        )

    body = "\n".join(rows) if rows else r"\multicolumn{6}{c}{No RGSA results} \\"
    return f"""% Generated by src/paper_statistics.py
\\begin{{table}}[htbp]
\\centering
\\caption{{RGSA comparison with published exact-method run times.  A dash denotes an unsolved or unreported class.  RGSA returns approximations; exact methods return feasibility certificates.}}
\\label{{tab:rgsa-literature}}
\\begin{{tabular}}{{rrrrrr}}
\\toprule
$m$ & $D$ & RGSA mean residual & RGSA time (s) & Wassermann time (s) & Kempke--Koch time (s) \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def generate_violations_table(
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
) -> str:
    """Mean max-violation V_max across classes and methods."""
    classes = sorted({(m, D) for (m, D, _) in class_statistics.keys()}, key=_row_key_sort)

    rows = []
    for m, D in classes:
        cells = []
        for config in CONFIG_ORDER:
            stats = class_statistics.get((m, D, config))
            if stats is None:
                cells.append("--")
                continue
            v = float(stats.get("mean_v_max", 0.0))
            cells.append(f"{v:.0f}")
        rows.append(f"{m} & {D} & " + " & ".join(cells) + r" \\")

    body = "\n".join(rows)
    return f"""% Generated by src/paper_statistics.py
\\begin{{table}}[htbp]
\\centering
\\caption{{Mean maximum row violation $V_{{\\max}}(x)=\\|Ax-b\\|_\\infty$ across seeds.  No method achieved exact feasibility (0/160 runs).}}
\\label{{tab:violations}}
\\footnotesize
\\begin{{tabular}}{{rr|rrrr}}
\\toprule
$m$ & $D$ & Blind SA & Lag.+Blind & RGSA & Full RGSA \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


