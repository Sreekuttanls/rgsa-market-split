def write_latex_tables(
    runs: Sequence[Mapping[str, Any]],
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
    output_dir: str | Path,
) -> list[Path]:
    """Generate all paper tables and return their paths."""
    destination = Path(output_dir)
    destination.mkdir(parents=True, exist_ok=True)
    tables = {
        "comprehensive_table.tex": generate_comprehensive_table(class_statistics),
        "scaling_table.tex": generate_scaling_table(class_statistics),
        "ablation_table.tex": generate_ablation_table(runs),
        "literature_comparison.tex": generate_literature_table(class_statistics),
        "best_residuals_table.tex": generate_best_residuals_table(runs),
        "violations_table.tex": generate_violations_table(class_statistics),
    }
    paths = []
    for filename, content in tables.items():
        path = destination / filename
        path.write_text(content, encoding="utf-8")
        paths.append(path)
    return paths


def print_summary(
    runs: Sequence[Mapping[str, Any]],
    class_statistics: Mapping[tuple[int, int, str], Mapping[str, float | int]],
    improvement: dict[str, float | int],
    table_paths: Sequence[Path],
) -> None:
    configs = sorted({str(run["config"]) for run in runs})
    feasible_count = sum(bool(run["feasible"]) for run in runs)
    print("RGSA paper benchmark statistics")
    print(f"  Runs: {len(runs)}")
    print(f"  Instances: {len({str(run['instance']) for run in runs})}")
    print(f"  Configurations ({len(configs)}): {', '.join(configs)}")
    print(f"  Class/config groups: {len(class_statistics)}")
    print(f"  Exact-feasible runs: {feasible_count}/{len(runs)} ({feasible_count / len(runs):.1%})")
    print(f"  Headline: RGSA vs Blind SA ({int(improvement['n_total'])} pairs)")
    print(f"    Mean improvement: {float(improvement['mean_improvement']):.3f} units")
    print(f"    Median improvement: {float(improvement['median_improvement']):.3f} units")
    print(f"    95% bootstrap CI: [{float(improvement['ci_lower']):.3f}, {float(improvement['ci_upper']):.3f}]")
    print(f"    RGSA better in {int(improvement['n_better'])}/{int(improvement['n_total'])} pairs")
    print("  LaTeX tables:")
    for path in table_paths:
        print(f"    {path}")


def build_argument_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Compute RGSA paper statistics and generate LaTeX tables."
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=DEFAULT_INPUT,
        help=f"benchmark results JSON (default: {DEFAULT_INPUT})",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"directory for generated .tex tables (default: {DEFAULT_OUTPUT_DIR})",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_argument_parser().parse_args(argv)
    runs = load_results(args.input)
    if not runs:
        raise ValueError(f"benchmark results file contains no runs: {args.input}")

    class_statistics = compute_per_class_statistics(runs)
    improvement = compute_improvement_stats(runs)
    table_paths = write_latex_tables(runs, class_statistics, args.output_dir)
    print_summary(runs, class_statistics, improvement, table_paths)
    return 0


